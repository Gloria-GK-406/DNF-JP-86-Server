"""Generate the full phase-2 sample table from the rewrite plan.

`generate_wrapper_pilot.py` emits 20 hand-picked samples chosen to be hot and
safe; this emits every entry `build_rewrite_plan.py` cleared, carrying the
per-entry patch mode it decided.

The plan already applied both geometric constraints (prefix landing points and
the gap to the next named entry), so no filtering happens here -- this is a
transcription step, and keeping it dumb is deliberate: one place decides
eligibility.

Usage:
  python generate_wrapper_pilot_full.py --plan wrapper-rewrite-plan.csv \
      --worklist wrapper-eligibility-worklist.csv \
      --out ../plugins/0150_wrapper_pilot/wrapper_pilot_full.h
"""
import argparse
import csv
import sys
from collections import Counter

IMAGE_BASE = 0x00400000
CONV = {"B": "WRAPPER_PILOT_CONV_B", "A": "WRAPPER_PILOT_CONV_A",
        "C": "WRAPPER_PILOT_CONV_C", "D": "WRAPPER_PILOT_CONV_D"}
BS = chr(92)


def cstr(text):
    return text.replace(BS, BS + BS).replace('"', BS + '"')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--plan", required=True)
    ap.add_argument("--worklist", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()

    wl = {r["entry_va"].lower(): r for r in
          csv.DictReader(open(a.worklist, encoding="utf-8-sig"))}
    plan = [r for r in csv.DictReader(open(a.plan, encoding="utf-8-sig"))
            if r["eligible"] == "YES"]
    plan.sort(key=lambda r: int(r["entry_va"], 16))

    rows, modes = [], []
    for r in plan:
        unit = wl[r["entry_va"].lower()]
        va = int(r["entry_va"], 16)
        site = int(unit["call_site_va"], 16)
        head = [int(x, 16) for x in unit["wrapper_head_hex"].split()][:10]
        rows.append(
            '    { 0x%08Xu, %s, "%s", "%s", 0x%08Xu,\n      { %s } },'
            % (va - IMAGE_BASE, CONV[r["group"]], cstr(r["module"]),
               cstr(r["function"]), site - IMAGE_BASE,
               ", ".join("0x%02X" % b for b in head)))
        modes.append(1 if r["patch_mode"] == "trampoline" else 0)

    body = (
        "/* Generated by ClientHack/tools/generate_wrapper_pilot_full.py from\n"
        " * wrapper-rewrite-plan.csv -- do not edit by hand.\n"
        " *\n"
        " * Every entry the eligibility census cleared, with both geometric\n"
        " * constraints applied: a patch may occupy\n"
        " *   min(safe_len, gap to the next named wrapper entry)\n"
        " * bytes. WRAPPER_PILOT_FULL_MODE[i] is 1 where that budget only fits\n"
        " * the 5-byte E9 trampoline and 0 where the inline template fits.\n"
        " */\n"
        "#ifndef CLIENTHACK_WRAPPER_PILOT_FULL_H\n"
        "#define CLIENTHACK_WRAPPER_PILOT_FULL_H\n\n"
        '#include "wrapper_pilot_samples.h"\n\n'
        "static const wrapper_pilot_sample_t WRAPPER_PILOT_FULL[] = {\n"
        + "\n".join(rows) + "\n};\n\n"
        "/* 0 = inline template at the entry, 1 = 5-byte E9 to a stub */\n"
        "static const uint8_t WRAPPER_PILOT_FULL_MODE[] = {\n"
        + "".join("    %d,%s" % (m, "\n" if (i + 1) % 16 == 0 else "")
                  for i, m in enumerate(modes)).rstrip(",\n") + "\n};\n\n"
        "#define WRAPPER_PILOT_FULL_COUNT %du\n\n#endif\n" % len(rows))

    open(a.out, "w", encoding="utf-8").write(body)
    print("entries      : %d" % len(rows))
    print("patch modes  : inline %d, trampoline %d"
          % (modes.count(0), modes.count(1)))
    print("by group     : %s" % dict(Counter(r["group"] for r in plan)))
    print("by module    : %s" % dict(Counter(r["module"] for r in plan).most_common(5)))
    print("wrote %s" % a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
